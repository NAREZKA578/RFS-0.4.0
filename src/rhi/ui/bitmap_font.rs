/// An 8×8 bitmap font that owns the atlas its glyphs live in.
///
/// Cells are laid out in a single row, one per codepoint, so a glyph's atlas
/// rectangle is its index times [`CELL`]. One row rather than a packed grid
/// because a grid would need a width that is known before the atlas exists, and
/// the atlas is created from this font.
pub struct UiBitmapFont {
    atlas_width: u32,
    atlas_height: u32,
    pixels: Vec<u8>,
}

/// One byte per texel: `0x20`..=`0x7E` laid out in one row of 8×8 cells.
///
/// The cell count alone is the *width*; the atlas is one cell tall, so the
/// buffer is width × height. Getting that wrong writes past the end of the
/// allocation on the very first glyph past the first row.
const ATLAS_SIZE: usize = ((LAST_CHAR - FIRST_CHAR + 1) * CELL as u32 * CELL as u32) as usize;

impl UiBitmapFont {
    /// Builds the font and its atlas.
    ///
    /// # Panics
    ///
    /// If the bitmap table is not exactly [`ATLAS_SIZE`] entries. That is a
    /// compile-time invariant of the table above, and a mismatch means a
    /// codepoint row is missing or duplicated, which would otherwise surface as
    /// one character silently drawing the wrong glyph.
    pub fn new() -> Self {
        let covered = BITMAPS.len();
        let expected = (LAST_CHAR - FIRST_CHAR + 1) as usize;
        assert_eq!(
            covered, expected,
            "the glyph table covers {covered} codepoints but {expected} are declared; \
             a missing or duplicated row would make one character draw another's glyph"
        );

        let atlas_width = expected as u32 * CELL as u32;
        let mut pixels = vec![0u8; ATLAS_SIZE];
        for (index, cell) in BITMAPS.iter().enumerate() {
            for (row, bits) in cell.iter().enumerate() {
                for bit in 0..CELL as u8 {
                    if bits & (1 << (CELL as u8 - 1 - bit)) != 0 {
                        let x = index as i32 * CELL + bit as i32;
                        let y = row as i32;
                        pixels[y as usize * atlas_width as usize + x as usize] = INK;
                    }
                }
            }
        }

        Self {
            atlas_width,
            atlas_height: CELL as u32,
            pixels,
        }
    }

    /// The atlas, one byte per texel: 0 is paper, 255 is full ink.
    pub fn atlas_pixels(&self) -> &[u8] {
        &self.pixels
    }

    /// Atlas width in texels.
    pub fn atlas_width(&self) -> u32 {
        self.atlas_width
    }

    /// Atlas height in texels.
    pub fn atlas_height(&self) -> u32 {
        self.atlas_height
    }

    fn index_of(ch: char) -> Option<usize> {
        let cp = ch as u32;
        (FIRST_CHAR..=LAST_CHAR).contains(&cp).then(|| (cp - FIRST_CHAR) as usize)
    }
}

impl Default for UiBitmapFont {
    fn default() -> Self {
        Self::new()
    }
}

impl UiFont for UiBitmapFont {
    fn glyph(&self, ch: char) -> Option<UiGlyph> {
        let index = Self::index_of(ch)?;
        if cell_is_blank(index) {
            // A space has no pixels, but it still moves the pen. Reported with a
            // zero rect and zero size so nothing is emitted for it, and the
            // advance does the work.
            return Some(UiGlyph {
                atlas_rect: [0.0, 0.0, 0.0, 0.0],
                offset: [0.0, 0.0],
                size: [0.0, 0.0],
                advance: CELL as f32,
            });
        }
        let x = index as f32 * CELL as f32;
        Some(UiGlyph {
            atlas_rect: [x, 0.0, x + CELL as f32, CELL as f32],
            offset: [0.0, 0.0],
            size: [CELL as f32, CELL as f32],
            advance: CELL as f32,
        })
    }

    fn natural_size(&self) -> f32 {
        CELL as f32
    }

    fn ascent(&self) -> f32 {
        // Cell height minus a two-texel descender, so text sits on a baseline
        // rather than hanging below it. An 8×8 cell has no real baseline, and
        // inventing one keeps the spacing readable.
        CELL as f32 - 2.0
    }

    fn descent(&self) -> f32 {
        2.0
    }
}