//! A bitmap font that carries its own atlas.
//!
//! # Why this exists
//!
//! [`UiFont`] was implemented only by layout-only fonts. They answered `glyph()`
//! with metrics so wrapping could be tested, and every one of them had no pixels
//! behind it. Nothing in the tree ever called `register_font` or `set_atlas`, so
//! the textured pipeline — which is complete and correct — could not run at all.
//!
//! Parsing a TTF is the real answer for shipping text, and it is a large,
//! self-contained piece of work. This is the part that has to exist first and is
//! genuinely useful on its own: glyphs with real coverage, an atlas they live in,
//! and an end-to-end path from `UiCommand::Text` to sampled pixels.
//!
//! `UiFont` stays the trait, so a TTF font can replace this one without touching
//! a caller. Nothing above this module knows glyphs come from an 8×8 table.
//!
//! # The bitmaps
//!
//! One byte per pixel, 8×8 cells, covering printable ASCII (`0x20`–`0x7E`).
//! Each cell is written as eight row bytes, top row first; a set bit is ink. The
//! shapes are deliberately plain. A legible typeface is not the goal here —
//! correct sampling, spacing and atlas layout are, because those are what a
//! replacement font would have to get right too, and they are what no amount of
//! unit testing of `glyph()` would catch.

use super::text::{UiFont, UiGlyph};

/// Glyph cell size in texels.
pub const CELL: i32 = 8;

/// First and last codepoint covered, inclusive.
pub const FIRST_CHAR: u32 = 0x20;
/// See [`FIRST_CHAR`].
pub const LAST_CHAR: u32 = 0x7E;

/// Whether the cell at `index` has no ink at all.
///
/// Per character, not once for the font. A font-wide "has a blank cell" flag
/// looked plausible next to the table's first row being a space, and it quietly
/// zeroed *every* glyph's size: the advance still advanced, so the text looked
/// laid out correctly while drawing nothing at all.
fn cell_is_blank(index: usize) -> bool {
    BITMAPS[index].iter().all(|row| *row == 0)
}

/// One byte per texel: 0 is paper, 255 is full ink.
const INK: u8 = 255;

/// Rows are top-first; a set bit is ink.
type Cell8 = [u8; CELL as usize];

/// ' ' — deliberately blank but present, so a space advances the pen.
